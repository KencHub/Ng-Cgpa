/**
 * Returns the institution object for the given ID, or null if not found.
 */
export function getInstitutionById(id) {
  return institutionRegistry.find((inst) => inst.id === id) || null;
}

/**
 * Returns all institutions whose name, shortName, ID, or location
 * contains the query string (case-insensitive). Returns full list if query is empty.
 */
export function searchInstitutions(query) {
  if (!query || query.trim() === "") return institutionRegistry;
  const q = query.trim().toLowerCase();
  return institutionRegistry.filter(
    (inst) =>
      inst.name.toLowerCase().includes(q) ||
      inst.shortName.toLowerCase().includes(q) ||
      inst.id.toLowerCase().includes(q) ||
      inst.location.toLowerCase().includes(q)
  );
}

/**
 * Returns all institutions matching a given scaleGroup.
 * Valid values: "NUC_5", "FOUR_POINT", "SEVEN_POINT", "CUSTOM"
 */
export function getInstitutionsByScale(scaleGroup) {
  return institutionRegistry.filter((inst) => inst.scaleGroup === scaleGroup);
}

/**
 * Returns all institutions of a given type.
 * Valid values: "Federal", "State", "Private", "Custom"
 */
export function getInstitutionsByType(type) {
  return institutionRegistry.filter((inst) => inst.type === type);
}

export default institutionRegistry;