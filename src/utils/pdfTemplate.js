// ── Degree Class Color ────────────────────────────────────────────────────────
export function classColor(shortClass) {
  if (!shortClass) return PDF_COLOR.textSecondary;
  const s = shortClass.toLowerCase();
  if (s.includes("first"))   return PDF_COLOR.classFirst;
  if (s.includes("2:1") || s.includes("upper")) return PDF_COLOR.classUpper;
  if (s.includes("2:2") || s.includes("lower")) return PDF_COLOR.classLower;
  if (s.includes("third"))   return PDF_COLOR.classThird;
  if (s.includes("pass"))    return PDF_COLOR.classPass;
  return PDF_COLOR.classFail;
}


