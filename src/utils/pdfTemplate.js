// ── Watermark ─────────────────────────────────────────────────────────────────

/**
 * Adds a faint diagonal watermark on the current page.
 * Uses GState for opacity. Falls back to near-white gray if GState is unsupported.
 */
export function addWatermark(doc) {
  const cx = PAGE_WIDTH  / 2;
  const cy = PAGE_HEIGHT / 2;

  try {
    doc.saveGraphicsState();
    const gs = doc.GState({ opacity: 0.07 });
    doc.setGState(gs);
    doc.setFont(PDF_FONT.bold.family, PDF_FONT.bold.style);
    doc.setFontSize(PDF_SIZE.watermark);
    doc.setTextColor(...PDF_COLOR.black);
    doc.text("NG CGPA  \u00B7  Nonso [ELUSK]", cx, cy, {
      align:    "center",
      angle:    45,
      baseline: "middle",
    });
    doc.restoreGraphicsState();
  } catch {
    doc.setFont(PDF_FONT.bold.family, PDF_FONT.bold.style);
    doc.setFontSize(PDF_SIZE.watermark);
    doc.setTextColor(248, 248, 248);
    doc.text("NG CGPA  \u00B7  Nonso [ELUSK]", cx, cy, {
      align:    "center",
      angle:    45,
      baseline: "middle",
    });
    doc.setTextColor(...PDF_COLOR.textPrimary);
  }
}


// ── Footer ────────────────────────────────────────────────────────────────────

/**
 * Adds the footer to the current page.
 * Two items only: brand text on the left, page number on the right.
 * Copyright line removed — it was clustering with the brand text at 7pt.
 */
export function addFooter(doc, pageNum, totalPages) {
  const y = PAGE_HEIGHT - MARGIN.bottom + 6;

  doc.setDrawColor(...PDF_COLOR.border);
  doc.setLineWidth(0.3);
  doc.line(MARGIN.left, y - 4, PAGE_WIDTH - MARGIN.right, y - 4);

  doc.setFont(PDF_FONT.regular.family, PDF_FONT.regular.style);
  doc.setFontSize(PDF_SIZE.micro);
  doc.setTextColor(...PDF_COLOR.textMuted);

  doc.text(
    "Generated by NG CGPA  |  ngcgpa.ng  |  Built by Nonso [ELUSK]",
    MARGIN.left,
    y,
    { baseline: "top" }
  );

  doc.text(
    `Page ${pageNum} of ${totalPages}`,
    PAGE_WIDTH - MARGIN.right,
    y,
    { align: "right", baseline: "top" }
  );
}


// ── Section Heading ───────────────────────────────────────────────────────────

export function addSectionHeading(doc, title, y) {
  doc.setFillColor(...PDF_COLOR.surface2);
  doc.rect(MARGIN.left, y, CONTENT_WIDTH, 8, "F");

  doc.setFont(PDF_FONT.bold.family, PDF_FONT.bold.style);
  doc.setFontSize(PDF_SIZE.h3);
  doc.setTextColor(...PDF_COLOR.primary);
  doc.text(title.toUpperCase(), MARGIN.left + 3, y + 4.5, {
    baseline: "middle",
  });

  return y + 10;
}


// ── Horizontal Rule ───────────────────────────────────────────────────────────
export function addRule(doc, y, color = PDF_COLOR.border) {
  doc.setDrawColor(...color);
  doc.setLineWidth(0.3);
  doc.line(MARGIN.left, y, PAGE_WIDTH - MARGIN.right, y);
  return y + 4;
}


// ── Key-Value Row ─────────────────────────────────────────────────────────────

export function addKV(doc, label, value, y, labelWidth = 48) {
  doc.setFont(PDF_FONT.bold.family, PDF_FONT.bold.style);
  doc.setFontSize(PDF_SIZE.body);
  doc.setTextColor(...PDF_COLOR.textSecondary);
  doc.text(label, MARGIN.left, y, { baseline: "top" });

  doc.setFont(PDF_FONT.regular.family, PDF_FONT.regular.style);
  doc.setTextColor(...PDF_COLOR.textPrimary);
  doc.text(String(value || "Not provided"), MARGIN.left + labelWidth, y, {
    baseline: "top",
  });

  return y + 6;
}


// ── GPA Bar (for trend section) ───────────────────────────────────────────────

export function addGPABar(doc, label, gpa, scaleMax, y, maxBarWidth = 80) {
  const BAR_HEIGHT = 4;
  const LABEL_W    = 52;
  const barAreaX   = MARGIN.left + LABEL_W;

  const ratio    = Math.min(Math.max(gpa / scaleMax, 0), 1);
  const barWidth = ratio * maxBarWidth;
  const color    = gpa >= scaleMax * 0.90 ? PDF_COLOR.classFirst
                 : gpa >= scaleMax * 0.70 ? PDF_COLOR.classUpper
                 : gpa >= scaleMax * 0.48 ? PDF_COLOR.classLower
                 : PDF_COLOR.danger;

  doc.setFont(PDF_FONT.regular.family, PDF_FONT.regular.style);
  doc.setFontSize(PDF_SIZE.small);
  doc.setTextColor(...PDF_COLOR.textSecondary);
  doc.text(truncateLabel(label, 28), MARGIN.left, y + BAR_HEIGHT / 2, {
    baseline: "middle",
  });

  doc.setFillColor(...PDF_COLOR.surface2);
  doc.roundedRect(barAreaX, y, maxBarWidth, BAR_HEIGHT, 1, 1, "F");

  if (barWidth > 0) {
    doc.setFillColor(...color);
    doc.roundedRect(barAreaX, y, barWidth, BAR_HEIGHT, 1, 1, "F");
  }

  doc.setFont(PDF_FONT.bold.family, PDF_FONT.bold.style);
  doc.setFontSize(PDF_SIZE.small);
  doc.setTextColor(...PDF_COLOR.textPrimary);
  doc.text(
    gpa !== null ? gpa.toFixed(2) : "\u2014",
    barAreaX + maxBarWidth + 3,
    y + BAR_HEIGHT / 2,
    { baseline: "middle" }
  );

  return y + BAR_HEIGHT + 3;
}


