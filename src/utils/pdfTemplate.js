// ── Helpers ───────────────────────────────────────────────────────────────────

function truncateLabel(str, max) {
  if (!str) return "";
  if (str.length <= max) return str;
  return str.slice(0, max - 1) + "\u2026";
}

export function generateRefId() {
  const hex = () => Math.floor(Math.random() * 65536).toString(16).toUpperCase().padStart(4, "0");
  return `${hex()}-${hex()}-${hex()}-${hex()}`;
}

export function formatPDFDate(date) {
  try {
    const d = date.toLocaleDateString("en-NG", {
      weekday: "long",
      day:     "numeric",
      month:   "long",
      year:    "numeric",
    });
    const t = date.toLocaleTimeString("en-NG", {
      hour:   "2-digit",
      minute: "2-digit",
      second: "2-digit",
      hour12: false,
    });
    return `${d} at ${t}`;
  } catch {
    return date.toISOString();
  }
}

export function safeStr(val, fallback = "Not provided") {
  if (val === null || val === undefined || String(val).trim() === "") return fallback;
  return String(val).trim();
}

export function fmtGPA(val) {
  if (val === null || val === undefined || isNaN(val)) return "\u2014";
  return Number(val).toFixed(2);
}